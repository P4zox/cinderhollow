def _paint(r, rows):
    assert len(rows) == r.h, (r.id, len(rows), r.h)
    for y, row in enumerate(rows):
        assert len(row) == r.w, (r.id, y, len(row), r.w)
        for x, ch in enumerate(row):
            r.g[y][x] = ch
    return r


def _deco(kind, x, y, **kw):
    return dict(t='sp_prop', kind=kind, x=x, y=y, **kw)


